#!/usr/bin/env node
/**
 * Writes one 1200x630 share card per prerendered page to public/og/<slug>.png and
 * the slug list to src/config/ogImages.ts.
 *
 * WHY. Every page used to share one 1024x1024 og-image.png while the runtime SEO
 * component declared 1200x630, so link previews on LinkedIn, Slack, Facebook and
 * X were mis-cropped and identical for all 88 pages.
 *
 * Run after `npm run build:seo` (titles are read from dist), then commit the
 * output. Cards are generated locally and committed on purpose: the build
 * machine may not have the same fonts, and a card with missing glyphs is worse
 * than none. A page without a card falls back to /og-image.png.
 *
 *   node scripts/generate-og-images.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const outDir = path.join(root, 'public/og');

export const slugFor = (route) => (route === '/' ? 'home' : route.replace(/^\/|\/$/g, '').replace(/\//g, '--'));

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function wrap(text, maxChars, maxLines) {
  const words = text.split(/\s+/);
  const lines = [];
  let cur = '';
  for (const w of words) {
    if ((cur + ' ' + w).trim().length > maxChars && cur) {
      lines.push(cur);
      cur = w;
    } else cur = (cur + ' ' + w).trim();
  }
  if (cur) lines.push(cur);
  if (lines.length > maxLines) {
    lines.length = maxLines;
    lines[maxLines - 1] = lines[maxLines - 1].replace(/[\s,:;.-]*\S*$/, '') + '…';
  }
  return lines;
}

function card(title, route) {
  const size = title.length > 70 ? 54 : title.length > 40 ? 62 : 72;
  const lines = wrap(title, Math.floor(1040 / (size * 0.53)), 4);
  const startY = 330 - ((lines.length - 1) * size * 1.18) / 2;
  const tspans = lines
    .map((l, i) => `<tspan x="80" y="${(startY + i * size * 1.18).toFixed(0)}">${esc(l)}</tspan>`)
    .join('');
  const shown = route === '/' ? 'realtordesk.ai' : 'realtordesk.ai' + route;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <rect width="1200" height="630" fill="#0B2540"/>
  <rect x="80" y="76" width="56" height="6" fill="#D7714E"/>
  <text x="80" y="132" font-family="Helvetica Neue, Helvetica, Arial, sans-serif" font-size="34" font-weight="700" fill="#FFFFFF">Realtor Desk</text>
  <text font-family="Helvetica Neue, Helvetica, Arial, sans-serif" font-size="${size}" font-weight="700" fill="#FFFFFF">${tspans}</text>
  <text x="80" y="560" font-family="Helvetica Neue, Helvetica, Arial, sans-serif" font-size="26" fill="#C9D6E4">${esc(shown.length > 70 ? shown.slice(0, 69) + '…' : shown)}</text>
  <text x="1120" y="560" text-anchor="end" font-family="Helvetica Neue, Helvetica, Arial, sans-serif" font-size="26" fill="#D7714E">CRM for Canadian agents</text>
</svg>`;
}

const sitemap = fs.readFileSync(path.join(root, 'public/sitemap.xml'), 'utf-8');
const routes = [...new Set([...sitemap.matchAll(/<loc>https:\/\/www\.realtordesk\.ai([^<]*)<\/loc>/g)].map((m) => m[1] || '/'))].sort();

fs.mkdirSync(outDir, { recursive: true });
const slugs = [];
for (const route of routes) {
  const file = route === '/' ? 'index.html' : path.join(route, 'index.html');
  const p = path.join(dist, file);
  if (!fs.existsSync(p)) {
    console.warn('skip (not prerendered): ' + route);
    continue;
  }
  const html = fs.readFileSync(p, 'utf-8');
  const raw = (html.match(/<title>([\s\S]*?)<\/title>/) || [])[1] || '';
  let title = raw.replace(/&amp;/g, '&').replace(/&#39;|&apos;/g, "'").replace(/&quot;/g, '"').replace(/\s*\|\s*Realtor Desk\s*$/, '').trim();
  if (route === '/') title = 'The real estate CRM for Canada';
  if (!title) continue;
  const slug = slugFor(route);
  await sharp(Buffer.from(card(title, route))).png({ compressionLevel: 9, palette: true }).toFile(path.join(outDir, slug + '.png'));
  slugs.push(slug);
}

fs.writeFileSync(
  path.join(root, 'src/config/ogImages.ts'),
  '// GENERATED by scripts/generate-og-images.mjs. Do not edit.\n' +
    '// Slugs that have a share card at /og/<slug>.png; any other page uses /og-image.png.\n' +
    'export const OG_IMAGE_SLUGS: ReadonlySet<string> = new Set([\n' +
    slugs.map((s) => '  ' + JSON.stringify(s) + ',').join('\n') +
    '\n]);\n',
);
console.log('✔ Wrote ' + slugs.length + ' cards to public/og and src/config/ogImages.ts');
